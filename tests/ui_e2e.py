# End-to-end UI test of the single-file build (file://), no AI key needed: uses the saved-extraction path.
import sys, os, json
from playwright.sync_api import sync_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHOTS = os.path.join(ROOT, 'out'); os.makedirs(SHOTS, exist_ok=True)
errors = []
with sync_playwright() as p:
    b = p.chromium.launch(headless=True)
    pg = b.new_page(viewport={'width': 1600, 'height': 1000}, accept_downloads=True)
    pg.on('console', lambda m: m.type == 'error' and errors.append(m.text))
    pg.on('pageerror', lambda e: errors.append(str(e)))
    pg.goto('file://' + os.path.join(ROOT, 'dist/GMM-ServiceCharge-Tool.html'))
    pg.wait_for_load_state('networkidle')
    pg.screenshot(path=f'{SHOTS}/ui_1_empty.png')
    pg.set_input_files('#xlsxInput', [os.path.join(ROOT, 'fixtures/Service Charge - Aug26.xlsx'), os.path.join(ROOT, 'fixtures/Incentive - Aug26.xlsx')])
    pg.wait_for_selector('text=Imported', timeout=30000)
    pg.click('.step[data-step="1"]')
    pg.wait_for_timeout(300)
    # attendance month July
    pg.fill('input[data-ws="attendanceMonth"]', '2026-07'); pg.dispatch_event('input[data-ws="attendanceMonth"]', 'change')
    pg.screenshot(path=f'{SHOTS}/ui_2_master.png', full_page=True)
    pg.click('.step[data-step="2"]')
    pg.set_input_files('#attInput', os.path.join(ROOT, 'fixtures/ATSB.pdf'))
    pg.wait_for_selector('.thumbs img', timeout=60000)
    pg.set_input_files('#extractInput', os.path.join(ROOT, 'fixtures/SAMPLE-genting-extraction-synthetic.json'))
    pg.wait_for_selector('text=What the AI read', timeout=10000)
    sel = pg.eval_on_selector('#attOutlet', 'e => e.options[e.selectedIndex].text')
    print('auto-picked outlet:', sel)
    pg.screenshot(path=f'{SHOTS}/ui_3_attendance.png', full_page=True)
    pg.click('[data-act="applyAtt"]')
    pg.wait_for_selector('#grid', timeout=10000)
    pv = pg.locator('.kpi.hl .v').first.inner_text()
    print('1 service point on screen:', pv)
    pg.screenshot(path=f'{SHOTS}/ui_4_review.png', full_page=False)
    # formula popover
    pg.click('th >> .qbtn[data-q="points"]')
    pg.wait_for_selector('#popover.open')
    print('popover:', pg.inner_text('#popover')[:300].replace('\n', ' | '))
    pg.screenshot(path=f'{SHOTS}/ui_5_popover.png')
    pg.keyboard.press('Escape')
    # click an entitled cell for a tier row (FAEZ)
    pg.click('tr:has-text("FAEZ") [data-cell="entitled"]')
    print('row popover:', pg.inner_text('#popover')[:400].replace('\n', ' | '))
    pg.keyboard.press('Escape')
    # open drawer
    pg.click('button.namebtn:has-text("CHEN CHOON MENG")')
    pg.wait_for_selector('#drawer.open')
    pg.screenshot(path=f'{SHOTS}/ui_6_drawer.png')
    pg.click('[data-act="closeDrawer"]')
    # override a value: set MC for a staff
    inp = pg.locator('tr:has-text("HADI A/L KUANG LEE") input[data-f="mc"]')
    inp.fill('4'); inp.press('Tab'); pg.wait_for_timeout(300)
    print('Hadi tier after MC=4:', pg.locator('tr:has-text("HADI A/L KUANG LEE") .tag.tier').inner_text())
    inp = pg.locator('tr:has-text("HADI A/L KUANG LEE") input[data-f="mc"]'); inp.fill('0'); inp.press('Tab'); pg.wait_for_timeout(300)
    # settings modal formulas tab
    pg.click('header [data-act="settings"]'); pg.click('[data-act="settingsTab"][data-tab="formulas"]')
    pg.screenshot(path=f'{SHOTS}/ui_7_formulas.png')
    pg.click('[data-act="settingsTab"][data-tab="ai"]'); pg.screenshot(path=f'{SHOTS}/ui_8_ai.png')
    pg.click('[data-act="closeSettings"]')
    # export
    pg.click('.step[data-step="4"]')
    pg.screenshot(path=f'{SHOTS}/ui_9_export.png', full_page=True)
    with pg.expect_download() as d: pg.click('[data-act="export"][data-s="sc"]')
    d.value.save_as(f'{SHOTS}/ui_ServiceCharge.xlsx'); print('downloaded', d.value.suggested_filename)
    with pg.expect_download() as d: pg.click('[data-act="export"][data-s="inc"]')
    d.value.save_as(f'{SHOTS}/ui_Incentive.xlsx'); print('downloaded', d.value.suggested_filename)
    b.close()
print('JS errors:', errors)
sys.exit(1 if errors else 0)
